CREATE DATABASE bdlaboratoriorm
    WITH
    OWNER = postgres
    ENCODING = 'UTF8'
    LC_COLLATE = 'Spanish_Nicaragua.1252'
    LC_CTYPE = 'Spanish_Nicaragua.1252'
    LOCALE_PROVIDER = 'libc'
    TABLESPACE = pg_default
    CONNECTION LIMIT = -1
    IS_TEMPLATE = False;

--
BEGIN;

CREATE SCHEMA IF NOT EXISTS laboratorio;

CREATE TABLE IF NOT EXISTS laboratorio.tipo_equipo (
    id_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(250)
);

CREATE TABLE IF NOT EXISTS laboratorio.equipo (
    id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    marca VARCHAR(100),
    estado VARCHAR(30) NOT NULL,
    cantidad INTEGER NOT NULL,

    id_tipo BIGINT NOT NULL,
    CONSTRAINT fk_equipo_tipo FOREIGN KEY (id_tipo)
        REFERENCES laboratorio.tipo_equipo(id_tipo) ON DELETE RESTRICT,
    CONSTRAINT ck_equipo_cantidad CHECK (cantidad >= 0),
    CONSTRAINT ck_equipo_estado CHECK (
        estado IN ('Disponible', 'En mantenimiento', 'Fuera de servicio')
    )
);

